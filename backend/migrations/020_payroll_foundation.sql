CREATE OR REPLACE FUNCTION prevent_final_payroll_line_changes()
RETURNS TRIGGER AS $$
DECLARE
  run_status VARCHAR(12);
BEGIN
  IF TG_OP <> 'INSERT' THEN
    SELECT status INTO run_status FROM payroll_runs WHERE id = OLD.payroll_run_id;
    IF run_status IS DISTINCT FROM 'draft' THEN
      RAISE EXCEPTION 'Payroll lines may only be changed while the payroll run is draft';
    END IF;
  END IF;

  IF TG_OP <> 'DELETE' THEN
    SELECT status INTO run_status FROM payroll_runs WHERE id = NEW.payroll_run_id;
    IF run_status IS DISTINCT FROM 'draft' THEN
      RAISE EXCEPTION 'Payroll lines may only be changed while the payroll run is draft';
    END IF;
    RETURN NEW;
  END IF;

  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS payroll_run_lines_draft_only ON payroll_run_lines;
CREATE TRIGGER payroll_run_lines_draft_only
  BEFORE INSERT OR UPDATE OR DELETE ON payroll_run_lines
  FOR EACH ROW EXECUTE FUNCTION prevent_final_payroll_line_changes();

CREATE OR REPLACE FUNCTION prevent_final_payroll_run_changes()
RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Payroll runs are retained for audit history';
  END IF;

  IF OLD.status = 'locked' THEN
    RAISE EXCEPTION 'Locked payroll runs are immutable';
  END IF;

  IF OLD.status <> NEW.status AND NOT (
    (OLD.status = 'draft' AND NEW.status = 'approved')
    OR (OLD.status = 'approved' AND NEW.status = 'locked')
  ) THEN
    RAISE EXCEPTION 'Invalid payroll run status transition';
  END IF;

  IF OLD.status = 'draft' AND NEW.status = 'approved'
     AND (to_jsonb(NEW) - ARRAY['status', 'approved_by', 'approved_at'])
       IS DISTINCT FROM (to_jsonb(OLD) - ARRAY['status', 'approved_by', 'approved_at']) THEN
    RAISE EXCEPTION 'Approval may only change payroll status and approval metadata';
  END IF;

  IF OLD.status = 'approved' AND NEW.status = 'locked'
     AND (to_jsonb(NEW) - ARRAY['status', 'locked_by', 'locked_at'])
       IS DISTINCT FROM (to_jsonb(OLD) - ARRAY['status', 'locked_by', 'locked_at']) THEN
    RAISE EXCEPTION 'Locking may only change payroll status and lock metadata';
  END IF;

  IF OLD.status = 'approved' AND NEW.status = 'approved'
     AND to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) THEN
    RAISE EXCEPTION 'Approved payroll runs may only transition to locked';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS payroll_runs_transition_only ON payroll_runs;
CREATE TRIGGER payroll_runs_transition_only
  BEFORE UPDATE OR DELETE ON payroll_runs
  FOR EACH ROW EXECUTE FUNCTION prevent_final_payroll_run_changes();

