CREATE OR REPLACE FUNCTION prevent_hrms_audit_changes() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'HRMS audit and payment records are append-only'; END;
$$;
REVOKE ALL ON FUNCTION prevent_hrms_audit_changes() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER attendance_reviews_append_only BEFORE UPDATE OR DELETE ON payroll_attendance_review_events
 FOR EACH ROW EXECUTE FUNCTION prevent_hrms_audit_changes();
CREATE TRIGGER payroll_payments_append_only BEFORE UPDATE OR DELETE ON payroll_payments
 FOR EACH ROW EXECUTE FUNCTION prevent_hrms_audit_changes();
CREATE OR REPLACE FUNCTION protect_confirmed_attendance() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE batch_state TEXT;
BEGIN
 IF TG_TABLE_NAME='payroll_attendance_import_batches' THEN
   IF OLD.review_state='confirmed' THEN RAISE EXCEPTION 'Confirmed attendance is immutable'; END IF;
 ELSE
   IF TG_OP='INSERT' THEN SELECT review_state INTO batch_state FROM payroll_attendance_import_batches WHERE id=NEW.batch_id;
   ELSE SELECT review_state INTO batch_state FROM payroll_attendance_import_batches WHERE id=OLD.batch_id; END IF;
   IF batch_state='confirmed' THEN RAISE EXCEPTION 'Confirmed attendance is immutable'; END IF;
   IF TG_OP='UPDATE' AND NEW.batch_id<>OLD.batch_id THEN
     SELECT review_state INTO batch_state FROM payroll_attendance_import_batches WHERE id=NEW.batch_id;
     IF batch_state='confirmed' THEN RAISE EXCEPTION 'Confirmed attendance is immutable'; END IF;
   END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION protect_confirmed_attendance() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER attendance_batch_confirmed_only BEFORE UPDATE OR DELETE ON payroll_attendance_import_batches
 FOR EACH ROW EXECUTE FUNCTION protect_confirmed_attendance();
CREATE TRIGGER attendance_days_confirmed_only BEFORE INSERT OR UPDATE OR DELETE ON payroll_daily_attendance
 FOR EACH ROW EXECUTE FUNCTION protect_confirmed_attendance();
